#!/usr/bin/env npx tsx
/**
 * Prerenders rankcli.dev's public pages into static HTML. Runs after
 * `vite build` as part of `pnpm build`.
 *
 * Why: GPTBot, ClaudeBot, PerplexityBot and Google's first pass don't run
 * JavaScript, so a client-rendered SPA shows them an empty <div id="root">
 * with the homepage's <head> on every URL.
 *
 * How: serve dist/ locally, open each public route (scripts/site-routes.ts)
 * in headless Chromium, wait for the page and its <SEO> head tags, and save
 * the DOM as dist/<route>.html. In the browser, main.tsx loads the page's
 * chunk and createRoot renders the same markup over it.
 *
 * Cloudflare Pages layout it produces:
 * - dist/<route>.html: served at /<route> (Pages drops the .html; a
 *   trailing-slash URL redirects to the bare one, matching the canonicals).
 * - dist/404.html: the NotFound page. With a top-level 404.html Pages stops
 *   treating the site as an SPA and answers unknown URLs with this page and
 *   a real 404 status.
 * - dist/app-shell.html + dist/_redirects: the unrendered SPA shell, served
 *   with 200 for every app route in src/routes.tsx (sign-in, dashboard,
 *   share links, OAuth callbacks), which would otherwise now 404.
 *
 * Browser: Playwright's Chromium (`pnpm exec playwright install chromium`),
 * or PRERENDER_CHROMIUM_PATH, or any Chromium under PLAYWRIGHT_BROWSERS_PATH
 * or ~/.cache/ms-playwright. Without one the step is skipped with a warning
 * and dist/ stays a plain SPA (no 404.html, so Pages keeps its SPA fallback),
 * unless PRERENDER=required, which fails the build. PRERENDER=skip skips it.
 */
import * as fs from 'node:fs';
import * as http from 'node:http';
import * as os from 'node:os';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium, type Browser } from '@playwright/test';
import { matchPath } from 'react-router-dom';
import { siteRoutes, routeUrl } from './site-routes';
import { publicRoutes, protectedRoutes } from '../src/routes';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(rootDir, 'dist');
const mode = (process.env.PRERENDER || 'auto').toLowerCase();

const SHELL_FILE = 'app-shell.html';
const SHELL_PATH = '/app-shell';
const NOT_FOUND_PROBE = '/__prerender_not_found__';
const CONCURRENCY = 4;
const PAGE_TIMEOUT_MS = 30_000;

// Old or mistyped URLs that are linked from outside the site (emails, the
// CLI's help text). Without SPA fallback these would now be hard 404s.
const LEGACY_REDIRECTS = [
  '/projects/:id /dashboard/projects/:id 301',
  '/docs/cli-setup /docs 301',
  '/docs/keywords /docs 301',
];

function log(message: string) {
  console.log(`prerender: ${message}`);
}

function fail(message: string): never {
  console.error(`prerender: ${message}`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Which routes are prerendered, and which are served by the SPA shell

/** Every route in src/routes.tsx must be prerendered or rewritten to the shell. */
function appRoutePatterns(): string[] {
  const appRoutes = [...publicRoutes.filter((route) => route.appTitle), ...protectedRoutes];
  const contentRoutes = publicRoutes.filter((route) => !route.appTitle);

  const unserved = contentRoutes.filter(
    (route) => !siteRoutes.some((site) => matchPath(route.path, site.path))
  );
  if (unserved.length) {
    fail(
      `these public routes are neither in scripts/site-routes.ts nor app routes, so they would 404: ` +
        unserved.map((route) => route.path).join(', ')
    );
  }
  return appRoutes.map((route) => route.path);
}

function redirectsFile(appPatterns: string[]) {
  return [
    '# Generated by scripts/prerender.ts. Do not edit; change src/routes.tsx.',
    '#',
    '# Public pages are prerendered to <route>.html and unknown URLs get',
    '# 404.html with a 404 status. App routes (sign-in, dashboard, share links)',
    '# are rendered in the browser, so they are served the SPA shell with 200.',
    // Exact paths before placeholder rules: Pages matches static rules faster.
    ...[...appPatterns].sort((a, b) => Number(a.includes(':')) - Number(b.includes(':'))).map(
      (pattern) => `${pattern} ${SHELL_PATH} 200`
    ),
    ...LEGACY_REDIRECTS,
    '',
  ].join('\n');
}

function outputFile(route: string) {
  if (route === '/') return 'index.html';
  if (route === NOT_FOUND_PROBE) return '404.html';
  return `${route.slice(1)}.html`;
}

// ---------------------------------------------------------------------------
// Chromium

function findChromium(): string | undefined {
  if (process.env.PRERENDER_CHROMIUM_PATH) return process.env.PRERENDER_CHROMIUM_PATH;

  try {
    const bundled = chromium.executablePath();
    if (bundled && fs.existsSync(bundled)) return undefined; // Playwright's own; launch() finds it
  } catch {
    // fall through to scanning
  }

  const cacheDirs = [
    process.env.PLAYWRIGHT_BROWSERS_PATH,
    path.join(os.homedir(), '.cache', 'ms-playwright'),
    path.join(os.homedir(), 'Library', 'Caches', 'ms-playwright'),
  ].filter((dir): dir is string => !!dir && fs.existsSync(dir));

  const binaries = [
    'chrome-headless-shell-linux64/chrome-headless-shell',
    'chrome-linux64/chrome',
    'chrome-linux/chrome',
    'chrome-headless-shell-mac-arm64/chrome-headless-shell',
    'chrome-headless-shell-mac-x64/chrome-headless-shell',
    'chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing',
    'chrome-mac/Chromium.app/Contents/MacOS/Chromium',
  ];

  const found: Array<{ revision: number; file: string }> = [];
  for (const dir of cacheDirs) {
    for (const entry of fs.readdirSync(dir)) {
      const match = /^chromium(?:_headless_shell)?-(\d+)$/.exec(entry);
      if (!match) continue;
      for (const binary of binaries) {
        const file = path.join(dir, entry, binary);
        if (fs.existsSync(file)) found.push({ revision: Number(match[1]), file });
      }
    }
  }
  found.sort((a, b) => b.revision - a.revision);
  return found[0]?.file ?? '';
}

async function launchBrowser(): Promise<Browser | null> {
  const executablePath = findChromium();
  if (executablePath === '') return null;
  try {
    return await chromium.launch(executablePath ? { executablePath } : {});
  } catch (error) {
    log(`could not launch Chromium: ${(error as Error).message.split('\n')[0]}`);
    return null;
  }
}

// ---------------------------------------------------------------------------
// Static server over dist/: files by path, everything else gets the shell

const contentTypes: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml',
  '.webmanifest': 'application/manifest+json',
};

function startServer(shellHtml: string): Promise<http.Server> {
  const server = http.createServer((req, res) => {
    const pathname = decodeURIComponent(new URL(req.url || '/', 'http://localhost').pathname);
    const file = path.join(distDir, pathname);
    const isAsset = path.extname(pathname) !== '' && file.startsWith(distDir);
    if (isAsset && fs.existsSync(file) && fs.statSync(file).isFile()) {
      res.writeHead(200, { 'Content-Type': contentTypes[path.extname(file)] || 'application/octet-stream' });
      fs.createReadStream(file).pipe(res);
      return;
    }
    if (isAsset) {
      res.writeHead(404).end();
      return;
    }
    // Navigation: always the unrendered shell, never an already-prerendered page.
    res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' }).end(shellHtml);
  });
  return new Promise((resolve) => server.listen(0, '127.0.0.1', () => resolve(server)));
}

// ---------------------------------------------------------------------------
// Rendering one route

interface Rendered {
  route: string;
  html: string;
  title: string;
}

async function renderRoute(browser: Browser, origin: string, route: string): Promise<Rendered> {
  const isNotFound = route === NOT_FOUND_PROBE;
  const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  try {
    await context.addInitScript(() => {
      window.__RANKCLI_PRERENDER__ = true;
    });
    // Only the local build: no Supabase, analytics or third-party fetches, so
    // the snapshot is the page's static content, the same on every build.
    await context.route('**/*', (request) =>
      request.request().url().startsWith(origin) ? request.continue() : request.abort()
    );

    const page = await context.newPage();
    const scripts = new Set<string>();
    const errors: string[] = [];
    page.on('request', (request) => {
      const url = new URL(request.url());
      if (url.origin === origin && url.pathname.startsWith('/assets/') && url.pathname.endsWith('.js')) {
        scripts.add(url.pathname);
      }
    });
    page.on('pageerror', (error) => errors.push(error.message));

    await page.goto(origin + route, { waitUntil: 'networkidle', timeout: PAGE_TIMEOUT_MS });

    // Ready when the page's own <SEO> tags are in the head: its canonical for
    // content pages, noindex for the 404 page.
    const expectedCanonical = isNotFound ? null : routeUrl(route);
    try {
      await page.waitForFunction(
        (canonical) => {
          const root = document.getElementById('root');
          if (!root?.firstElementChild) return false;
          if (canonical === null) return !!document.querySelector('meta[name="robots"][data-rh]');
          return document.querySelector('link[rel="canonical"]')?.getAttribute('href') === canonical;
        },
        expectedCanonical,
        { timeout: PAGE_TIMEOUT_MS }
      );
    } catch {
      const canonical = await page.evaluate(() => document.querySelector('link[rel="canonical"]')?.getAttribute('href'));
      throw new Error(
        `${route}: page never got ready (canonical ${canonical ?? 'missing'}, expected ${expectedCanonical ?? 'noindex'})` +
          (errors.length ? `; page errors: ${errors.join(' | ')}` : '')
      );
    }
    // Let Helmet's deferred head update and any last effects settle.
    await page.waitForLoadState('networkidle');
    await page.waitForTimeout(150);

    const result = await page.evaluate((preloads) => {
      // Prerendered pages have their real content; the no-JS fallback blurb
      // (and its second <h1>) is only for the shell.
      document.querySelectorAll('noscript').forEach((node) => node.remove());

      // Third-party tags that inject their own <script> get captured twice: once as the inline
      // loader we shipped, and once as the element that loader created while this page was
      // being rendered. Serving both means the loader runs again in the visitor's browser and
      // adds a third, so the vendor script loads twice and every event fires twice. Remove what
      // the loader created; it will recreate it at runtime, exactly once.
      document
        .querySelectorAll('script[src*="redditstatic.com/ads"], script[src*="cloudflareinsights.com"]')
        .forEach((node) => {
          // Keep anything we put in the HTML ourselves; only drop what was injected at runtime.
          if (!node.hasAttribute('data-cf-beacon')) node.remove();
        });

      // Fetch this page's chunks in parallel with the entry script instead of
      // after it: main.tsx won't render until they're loaded.
      const linked = new Set(
        Array.from(document.querySelectorAll('script[src], link[rel="modulepreload"]')).map(
          (node) => new URL(node.getAttribute('src') || node.getAttribute('href') || '', location.href).pathname
        )
      );
      for (const src of preloads) {
        if (linked.has(src)) continue;
        const link = document.createElement('link');
        link.rel = 'modulepreload';
        link.crossOrigin = '';
        link.href = src;
        document.head.appendChild(link);
      }

      const root = document.getElementById('root')!;
      return {
        html: '<!DOCTYPE html>\n' + document.documentElement.outerHTML + '\n',
        title: document.title,
        h1Count: root.querySelectorAll('h1').length,
        noindex: !!document.querySelector('meta[name="robots"][content*="noindex"]'),
        textLength: (root.textContent || '').trim().length,
      };
    }, [...scripts]);

    if (result.h1Count !== 1) throw new Error(`${route}: expected one <h1>, found ${result.h1Count}`);
    if (!isNotFound && result.noindex) throw new Error(`${route}: rendered as noindex (NotFound?)`);
    if (result.textLength < 200) throw new Error(`${route}: only ${result.textLength} characters of content`);
    if (errors.length) log(`warning: ${route} logged page errors: ${errors.join(' | ')}`);

    return { route, html: result.html, title: result.title };
  } finally {
    await context.close();
  }
}

// ---------------------------------------------------------------------------

async function main() {
  if (mode === 'skip' || mode === '0' || mode === 'false') {
    log('skipped (PRERENDER=skip)');
    return;
  }
  const required = mode === 'required' || mode === 'require';

  const shellFile = path.join(distDir, 'index.html');
  if (!fs.existsSync(shellFile)) fail('dist/index.html not found; run `vite build` first.');
  const shellHtml = fs.readFileSync(shellFile, 'utf8');
  if (shellHtml.includes('data-prerendered')) fail('dist/index.html is already prerendered; run `vite build` first.');

  const appPatterns = appRoutePatterns();

  const browser = await launchBrowser();
  if (!browser) {
    const message =
      'no Chromium found, so pages were NOT prerendered and dist/ is a plain SPA. ' +
      'Install one with `pnpm exec playwright install chromium`, or set PRERENDER_CHROMIUM_PATH.';
    if (required) fail(message);
    log(`warning: ${message}`);
    return;
  }

  const server = await startServer(shellHtml);
  const { port } = server.address() as { port: number };
  const origin = `http://127.0.0.1:${port}`;

  const routes = [...siteRoutes.map((route) => route.path), NOT_FOUND_PROBE];
  const rendered: Rendered[] = [];
  const failures: string[] = [];
  try {
    const queue = [...routes];
    await Promise.all(
      Array.from({ length: CONCURRENCY }, async () => {
        for (let route = queue.shift(); route; route = queue.shift()) {
          try {
            rendered.push(await renderRoute(browser, origin, route));
          } catch (error) {
            failures.push((error as Error).message);
          }
        }
      })
    );
  } finally {
    await browser.close();
    server.close();
  }
  if (failures.length) fail(`${failures.length} page(s) failed:\n  ${failures.join('\n  ')}`);

  const titles = new Map<string, string>();
  for (const page of rendered) {
    const other = titles.get(page.title);
    if (other && page.route !== NOT_FOUND_PROBE) log(`warning: ${page.route} and ${other} share the title "${page.title}"`);
    titles.set(page.title, page.route);
  }

  // Write everything only once every page rendered, so a failure can't leave
  // a half-prerendered dist/.
  const noindexShell = shellHtml.replace(
    '<head>',
    '<head>\n    <meta name="robots" content="noindex, nofollow" />'
  );
  fs.writeFileSync(path.join(distDir, SHELL_FILE), noindexShell);
  for (const page of rendered) {
    const file = path.join(distDir, outputFile(page.route));
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, page.html.replace('<div id="root">', '<div id="root" data-prerendered="">'));
  }
  fs.writeFileSync(path.join(distDir, '_redirects'), redirectsFile(appPatterns));

  log(
    `${rendered.length - 1} pages + 404.html written; ${appPatterns.length} app routes served by ${SHELL_FILE}`
  );
}

main().catch((error) => fail((error as Error).stack || String(error)));
