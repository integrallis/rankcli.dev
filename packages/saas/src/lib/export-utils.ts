import type { AuditIssue } from '@/integrations/supabase/types';

// Category display labels
const CATEGORY_LABELS: Record<string, string> = {
  crawlability: 'Crawlability',
  indexability: 'Indexability',
  'on-page': 'On-Page',
  content: 'Content',
  links: 'Links',
  images: 'Images',
  'structured-data': 'Structured Data',
  performance: 'Performance',
  security: 'Security',
  mobile: 'Mobile',
  international: 'International',
  'ai-readiness': 'AI Readiness',
  social: 'Social',
  'local-seo': 'Local SEO',
  accessibility: 'Accessibility',
};

/**
 * Group issues by severity
 */
function groupBySeverity(issues: AuditIssue[]): Record<string, AuditIssue[]> {
  const groups: Record<string, AuditIssue[]> = {
    error: [],
    warning: [],
    notice: [],
  };

  for (const issue of issues) {
    if (groups[issue.severity]) {
      groups[issue.severity].push(issue);
    }
  }

  return groups;
}

/**
 * Build full URL from path and project URL
 */
function getFullUrl(url: string, projectUrl: string): string {
  try {
    new URL(url);
    return url;
  } catch {
    try {
      const base = new URL(projectUrl);
      return new URL(url, base).href;
    } catch {
      return url;
    }
  }
}

/**
 * Export issues to Markdown format
 */
export function exportToMarkdown(
  issues: AuditIssue[],
  projectName: string,
  projectUrl: string
): void {
  const grouped = groupBySeverity(issues);
  const date = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  let markdown = `# SEO Audit Report: ${projectName}\n\n`;
  markdown += `**URL:** ${projectUrl}\n`;
  markdown += `**Date:** ${date}\n\n`;

  // Summary
  const errorCount = grouped.error.length;
  const warningCount = grouped.warning.length;
  const noticeCount = grouped.notice.length;

  markdown += `## Summary\n\n`;
  markdown += `| Severity | Count |\n`;
  markdown += `|----------|-------|\n`;
  markdown += `| Errors   | ${errorCount} |\n`;
  markdown += `| Warnings | ${warningCount} |\n`;
  markdown += `| Notices  | ${noticeCount} |\n`;
  markdown += `| **Total** | **${issues.length}** |\n\n`;

  // Issues by severity
  const severityLabels: Record<string, string> = {
    error: 'Errors',
    warning: 'Warnings',
    notice: 'Notices',
  };

  const severityEmojis: Record<string, string> = {
    error: '🔴',
    warning: '🟡',
    notice: '🔵',
  };

  for (const severity of ['error', 'warning', 'notice']) {
    const severityIssues = grouped[severity];
    if (severityIssues.length === 0) continue;

    markdown += `## ${severityEmojis[severity]} ${severityLabels[severity]} (${severityIssues.length})\n\n`;

    for (const issue of severityIssues) {
      const categoryLabel = CATEGORY_LABELS[issue.category] || issue.category;

      markdown += `### ${issue.title}\n\n`;
      markdown += `**Category:** ${categoryLabel}\n`;
      markdown += `**Code:** \`${issue.code}\`\n\n`;

      if (issue.description) {
        markdown += `**Description:**\n${issue.description}\n\n`;
      }

      if (issue.impact) {
        markdown += `**Impact:**\n${issue.impact}\n\n`;
      }

      if (issue.how_to_fix) {
        markdown += `**How to Fix:**\n${issue.how_to_fix}\n\n`;
      }

      if (issue.affected_urls && issue.affected_urls.length > 0) {
        markdown += `**Affected Pages (${issue.affected_urls.length}):**\n`;
        for (const url of issue.affected_urls) {
          const fullUrl = getFullUrl(url, projectUrl);
          markdown += `- ${fullUrl}\n`;
        }
        markdown += '\n';
      }

      markdown += `---\n\n`;
    }
  }

  markdown += `\n---\n\n*Generated by [RankCLI](https://rankcli.dev)*\n`;

  // Download the file
  const blob = new Blob([markdown], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `seo-audit-${projectName.toLowerCase().replace(/\s+/g, '-')}-${new Date().toISOString().split('T')[0]}.md`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Export issues to PDF using browser print dialog
 */
export function exportToPDF(
  issues: AuditIssue[],
  projectName: string,
  projectUrl: string
): void {
  const grouped = groupBySeverity(issues);
  const date = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  // Create a printable HTML document
  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    alert('Please allow popups to export PDF');
    return;
  }

  const severityLabels: Record<string, string> = {
    error: 'Errors',
    warning: 'Warnings',
    notice: 'Notices',
  };

  const severityColors: Record<string, string> = {
    error: '#ef4444',
    warning: '#eab308',
    notice: '#3b82f6',
  };

  let issuesHtml = '';

  for (const severity of ['error', 'warning', 'notice']) {
    const severityIssues = grouped[severity];
    if (severityIssues.length === 0) continue;

    issuesHtml += `
      <section class="severity-group">
        <h2 style="color: ${severityColors[severity]}; display: flex; align-items: center; gap: 8px;">
          <span style="display: inline-block; width: 12px; height: 12px; border-radius: 50%; background: ${severityColors[severity]};"></span>
          ${severityLabels[severity]} (${severityIssues.length})
        </h2>
    `;

    for (const issue of severityIssues) {
      const categoryLabel = CATEGORY_LABELS[issue.category] || issue.category;

      issuesHtml += `
        <div class="issue">
          <h3>${issue.title}</h3>
          <p class="meta"><strong>Category:</strong> ${categoryLabel} | <strong>Code:</strong> <code>${issue.code}</code></p>
      `;

      if (issue.description) {
        issuesHtml += `<p><strong>Description:</strong> ${issue.description}</p>`;
      }

      if (issue.impact) {
        issuesHtml += `<p><strong>Impact:</strong> ${issue.impact}</p>`;
      }

      if (issue.how_to_fix) {
        issuesHtml += `<p><strong>How to Fix:</strong> ${issue.how_to_fix}</p>`;
      }

      if (issue.affected_urls && issue.affected_urls.length > 0) {
        issuesHtml += `<p><strong>Affected Pages (${issue.affected_urls.length}):</strong></p><ul>`;
        for (const url of issue.affected_urls.slice(0, 10)) {
          const fullUrl = getFullUrl(url, projectUrl);
          issuesHtml += `<li><code>${fullUrl}</code></li>`;
        }
        if (issue.affected_urls.length > 10) {
          issuesHtml += `<li><em>... and ${issue.affected_urls.length - 10} more</em></li>`;
        }
        issuesHtml += `</ul>`;
      }

      issuesHtml += `</div>`;
    }

    issuesHtml += `</section>`;
  }

  const html = `
    <!DOCTYPE html>
    <html>
    <head>
      <title>SEO Audit Report - ${projectName}</title>
      <link rel="preconnect" href="https://fonts.googleapis.com">
      <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
      <link href="https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600&display=swap" rel="stylesheet">
      <style>
        * { box-sizing: border-box; }
        body {
          font-family: 'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
          font-weight: 400;
          line-height: 1.6;
          max-width: 800px;
          margin: 0 auto;
          padding: 40px 20px;
          color: #1a1a1a;
        }
        .summary, .issue {
          font-weight: 300;
        }
        h1 { margin-bottom: 8px; }
        .subtitle { color: #666; margin-bottom: 24px; }
        .summary {
          background: #f5f5f5;
          padding: 16px 24px;
          border-radius: 8px;
          margin-bottom: 24px;
        }
        .summary table { width: 100%; border-collapse: collapse; }
        .summary th, .summary td { text-align: left; padding: 8px 0; }
        .summary th { border-bottom: 1px solid #ddd; }
        .severity-group { margin-bottom: 32px; }
        .issue {
          border: 1px solid #e5e5e5;
          border-radius: 8px;
          padding: 16px;
          margin-bottom: 16px;
          page-break-inside: avoid;
        }
        .issue h3 { margin: 0 0 8px 0; }
        .issue .meta { color: #666; font-size: 14px; margin-bottom: 12px; }
        .issue p { margin: 8px 0; }
        .issue ul { margin: 8px 0; padding-left: 20px; }
        .issue li { margin: 4px 0; }
        code {
          background: #f0f0f0;
          padding: 2px 6px;
          border-radius: 4px;
          font-size: 13px;
        }
        .footer {
          margin-top: 40px;
          padding-top: 20px;
          border-top: 1px solid #e5e5e5;
          text-align: center;
          color: #666;
          font-size: 14px;
        }
        @media print {
          body { padding: 20px; }
          .issue { break-inside: avoid; }
        }
      </style>
    </head>
    <body>
      <h1>SEO Audit Report</h1>
      <p class="subtitle">
        <strong>${projectName}</strong><br>
        ${projectUrl}<br>
        ${date}
      </p>

      <div class="summary">
        <h2 style="margin-top: 0;">Summary</h2>
        <table>
          <tr><th>Severity</th><th>Count</th></tr>
          <tr><td>Errors</td><td>${grouped.error.length}</td></tr>
          <tr><td>Warnings</td><td>${grouped.warning.length}</td></tr>
          <tr><td>Notices</td><td>${grouped.notice.length}</td></tr>
          <tr><th>Total</th><th>${issues.length}</th></tr>
        </table>
      </div>

      ${issuesHtml}

      <div class="footer">
        Generated by <a href="https://rankcli.dev">RankCLI</a>
      </div>
    </body>
    </html>
  `;

  printWindow.document.write(html);
  printWindow.document.close();

  // Wait for content to load then trigger print
  printWindow.onload = () => {
    printWindow.print();
  };
}
